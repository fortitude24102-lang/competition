#ifndef V3_CONTROL_PROTOCOL_H
#define V3_CONTROL_PROTOCOL_H
#include <stdint.h>

#define V3_CONTROL_MAGIC UINT32_C(0x41474331)
#define V3_TELEMETRY_MAGIC UINT32_C(0x41475431)
#define V3_PROTOCOL_VERSION 1u
#define V3_PACKET_HELLO 1u
#define V3_PACKET_KEYS 2u
#define V3_PACKET_ACK 3u
#define V3_PACKET_GAME 4u
#define V3_PACKET_GAME_ACK 5u
#define V3_GAME_START 1u
#define V3_GAME_MENU 2u
#define V3_PACKET_TELEMETRY 0x80u
#define V3_CONTROL_BYTES 32u
#define V3_TELEMETRY_BYTES 128u
#define V3_TELEMETRY_FIELDS 27u
#define V3_INPUT_LEASE_MS 250u
#define V3_POLL_MAX_PACKETS 4u
#define V3_TELEMETRY_DEFAULT_MS 200u
#define V3_TELEMETRY_MIN_MS 100u
#define V3_KEY_LEFT UINT16_C(0x01)
#define V3_KEY_RIGHT UINT16_C(0x02)
#define V3_KEY_UP UINT16_C(0x04)
#define V3_KEY_DOWN UINT16_C(0x08)
#define V3_KEY_FIRE UINT16_C(0x10)
#define V3_KEY_SLOW UINT16_C(0x20)
#define V3_KEY_RESTART UINT16_C(0x40)
#define V3_KEY_COMPARE UINT16_C(0x80)
#define V3_KEY_MASK UINT16_C(0xff)
#define V3_KEY_ACTION_MASK (V3_KEY_RESTART | V3_KEY_COMPARE)

#define V3_STATUS_GPU_REALTIME (UINT32_C(1) << 0)
#define V3_STATUS_COMPARE_REPLAY (UINT32_C(1) << 1)
#define V3_STATUS_LOADING (UINT32_C(1) << 2)
#define V3_STATUS_LOCAL_FALLBACK (UINT32_C(1) << 3)
#define V3_STATUS_CONTROL_CONNECTED (UINT32_C(1) << 4)
#define V3_STATUS_CPU_STALE (UINT32_C(1) << 5)
#define V3_STATUS_PROBES_ENABLED (UINT32_C(1) << 6)
#define V3_STATUS_INVALID_COUNTS (UINT32_C(1) << 7)
#define V3_STATUS_PAUSED (UINT32_C(1) << 8)
#define V3_STATUS_ERROR_RECOVERY (UINT32_C(1) << 9)
#define V3_STATUS_MENU (UINT32_C(1) << 10)
#define V3_STATUS_GAME_MENU_CAPABLE (UINT32_C(1) << 11)
#define V3_VALID_GPU_TIMING (UINT32_C(1) << 16)
#define V3_VALID_CPU_FPS (UINT32_C(1) << 17)
#define V3_VALID_PROBES (UINT32_C(1) << 18)
#define V3_VALID_TRAFFIC (UINT32_C(1) << 19)
#define V3_VALID_ERRORS (UINT32_C(1) << 20)
#define V3_VALID_INPUT_NETWORK (UINT32_C(1) << 21)
#define V3_VALID_ALPHA_KEY (UINT32_C(1) << 22)
#define V3_STATUS_ALLOWED_MASK UINT32_C(0x007f0fff)

/* Offsets are relative to the existing GPU_APB_BASE, not a new base. */
#define NC_ID_VALUE UINT32_C(0x4d475431)
#define NC_REG_ID 0x0300u
#define NC_REG_STATUS 0x0304u
#define NC_REG_RX_SNAPSHOT 0x0308u
#define NC_REG_RX_RELEASE 0x030cu
#define NC_REG_RX_AGE_MS 0x0310u
#define NC_REG_RX_DROP_COUNT 0x0314u
#define NC_REG_TX_COMMIT 0x0318u
#define NC_REG_TX_DONE_COUNT 0x031cu
#define NC_REG_RX_WORD0 0x0320u
#define NC_REG_TX_WORD0 0x0340u
#define NC_REG_TX_LENGTH 0x03c0u
#define NC_STATUS_RX_AVAILABLE (UINT32_C(1) << 0)
#define NC_STATUS_RX_SNAPSHOT_VALID (UINT32_C(1) << 1)
#define NC_STATUS_TX_READY (UINT32_C(1) << 2)
#define NC_STATUS_TX_ERROR (UINT32_C(1) << 3)
#endif
