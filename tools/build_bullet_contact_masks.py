"""Precompute the existing 8x8 texel/disk contact test, without approximation."""
import argparse
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
OUTPUT = ROOT / "sw/efinix_gpu/include/bullet_contact_masks.h"
ROWS = (
    (0x00, 0x3c, 0x7e, 0x7e, 0x7e, 0x7e, 0x3c, 0x00),
    (0x18, 0x3c, 0x7e, 0xff, 0xff, 0x7e, 0x3c, 0x18),
    (0x18, 0x18, 0x3c, 0x3c, 0x3c, 0x3c, 0x18, 0x18),
    (0x18, 0x18, 0x18, 0xff, 0xff, 0x18, 0x18, 0x18),
    (0x99, 0x5a, 0x3c, 0xff, 0xff, 0x3c, 0x5a, 0x99),
    (0x00, 0x3c, 0x66, 0x42, 0x42, 0x66, 0x3c, 0x00),
)


def render():
    lines = ["/* Generated by tools/build_bullet_contact_masks.py; do not edit.",
             " * Bit x+19 in row y+19: a texel at offset (x,y) touches the disk.",
             " * Shape x {hit radius 3, graze radius 12} x relative y. */",
             "static const uint32_t bullet_contact_masks[6][2][32]={"]
    for shape in ROWS:
        lines.append(" {")
        for radius in (3, 12):
            words = []
            for dy in range(-19, 13):
                word = 0
                for dx in range(-19, 13):
                    if any(shape[y] & (1 << x) and
                           (dx + x)**2 + (dy + y)**2 <= radius**2
                           for y in range(8) for x in range(8)):
                        word |= 1 << (dx + 19)
                words.append(f"0x{word:08x}u")
            lines.append("  {")
            for i in range(0, 32, 4):
                lines.append("   " + ",".join(words[i:i+4]) + ",")
            lines.append("  },")
        lines.append(" },")
    return "\n".join(lines + ["};", ""])


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    expected = render()
    if args.check:
        if not OUTPUT.exists() or OUTPUT.read_text() != expected:
            raise SystemExit("FAIL: contact masks missing or stale; regenerate")
        print("PASS: contact masks reproduce exactly (1536 bytes)")
    else:
        OUTPUT.write_text(expected)
